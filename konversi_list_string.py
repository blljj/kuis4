# Data hobi dalam List
hobi = ["Shopping", "Travelling", "Dancing"]

# Casting List ke String
data_hobi = str(hobi)

# Menggabungkan elemen List menjadi String
hobi_string = ", ".join(hobi)

# Menampilkan hasil
print("Data List       :", hobi)
